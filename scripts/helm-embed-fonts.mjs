// Codegen: read the 5 brand TTFs and emit src/lib/helm/fonts.generated.ts
// exporting FONT_FACE_CSS (base64 @font-face). The Lambda chromium has no
// system fonts, so the proposal renderer embeds these inline. Re-run after
// changing the fonts:  node scripts/helm-embed-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const FONTS = path.resolve("src/lib/helm/assets/fonts");

// Same families / weight ranges / styles as font_face_css() in
// render-kit/scripts/build_proposal.py — 1:1.
const FACES = [
  { family: "Cinzel", file: "Cinzel.ttf", weight: "400 900", style: "normal" },
  { family: "Montserrat", file: "Montserrat.ttf", weight: "100 900", style: "normal" },
  { family: "Montserrat", file: "Montserrat-Italic.ttf", weight: "100 900", style: "italic" },
  { family: "Cormorant", file: "Cormorant.ttf", weight: "300 700", style: "normal" },
  { family: "Cormorant", file: "Cormorant-Italic.ttf", weight: "300 700", style: "italic" },
];

const css = FACES.map((f) => {
  const b64 = readFileSync(path.join(FONTS, f.file)).toString("base64");
  return (
    `@font-face{font-family:'${f.family}';font-style:${f.style};` +
    `font-weight:${f.weight};src:url(data:font/ttf;base64,${b64}) format('truetype');}`
  );
}).join("\n");

const out =
  `// AUTO-GENERATED by scripts/helm-embed-fonts.mjs — do not edit by hand.\n` +
  `// 5 brand TTFs (Cinzel, Cormorant, Cormorant-Italic, Montserrat,\n` +
  `// Montserrat-Italic; OFL) base64-embedded as @font-face. Lambda chromium\n` +
  `// has no system fonts, so the proposal renderer MUST embed these inline.\n` +
  `/* eslint-disable */\n` +
  `export const FONT_FACE_CSS = ${JSON.stringify(css)};\n`;

writeFileSync(path.resolve("src/lib/helm/fonts.generated.ts"), out);
console.log(`wrote src/lib/helm/fonts.generated.ts (${(out.length / 1024 / 1024).toFixed(2)} MB)`);
